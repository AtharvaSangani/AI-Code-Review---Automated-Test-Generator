"""Pydantic v2 Request and Response Schemas."""

from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


# ==============================================================================
# Generate Tests Schemas
# ==============================================================================

class GenerateTestsRequest(BaseModel):
    """Payload for submitting source code to generate unit tests."""

    function_name: str = Field(
        ...,
        description="Target function name to generate unit tests for.",
        examples=["binary_search"],
    )
    source_code: str = Field(
        ...,
        description="Complete Python source code containing the target function.",
        examples=[
            "def binary_search(arr, target):\n"
            "    left, right = 0, len(arr) - 1\n"
            "    while left <= right:\n"
            "        mid = (left + right) // 2\n"
            "        if arr[mid] == target:\n"
            "            return mid\n"
            "        elif arr[mid] < target:\n"
            "            left = mid + 1\n"
            "        else:\n"
            "            right = mid - 1\n"
            "    return -1"
        ],
    )
    framework: str = Field(
        default="pytest",
        description="Testing framework target. Currently pytest is standard.",
    )


class GenerateTestsResponse(BaseModel):
    """Deterministic verification result from the sandbox runner."""

    status: str = Field(
        ...,
        description="Status of the generation process: 'success' or 'failed'.",
        examples=["success"],
    )
    tests_generated: int = Field(
        ...,
        ge=0,
        description="Count of test functions generated by the LLM.",
        examples=[4],
    )
    verdict: Literal["VERIFIED_PASSING", "REJECTED_HALLUCINATION"] = Field(
        ...,
        description="Deterministic verification verdict.",
        examples=["VERIFIED_PASSING"],
    )
    test_code: str = Field(
        ...,
        description="Generated pytest test code.",
    )
    execution_time_ms: float = Field(
        ...,
        description="Sandbox pytest execution time in milliseconds.",
        examples=[45.2],
    )
    stdout: str = Field(
        ...,
        description="Standard output captured from the pytest runner.",
    )
    stderr: Optional[str] = Field(
        default="",
        description="Standard error captured from the pytest runner.",
    )
    diagnostics: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Structured diagnostics detailing failure or hallucination reasons.",
    )


# ==============================================================================
# Code Review Schemas
# ==============================================================================

class ReviewCodeRequest(BaseModel):
    """Payload for requesting static and LLM code review."""

    source_code: str = Field(
        ...,
        description="Python source code to analyze.",
        examples=[
            "def find_duplicates(nums):\n"
            "    res = []\n"
            "    for i in range(len(nums)):\n"
            "        for j in range(i+1, len(nums)):\n"
            "            if nums[i] == nums[j]:\n"
            "                res.append(nums[i])\n"
            "    return res"
        ],
    )


class Flake8Issue(BaseModel):
    """Individual linter issue detected by Flake8."""

    line: int = Field(..., description="Line number where issue was found.")
    col: int = Field(..., description="Column offset.")
    code: str = Field(..., description="Flake8 rule code (e.g. E302, W291).")
    message: str = Field(..., description="Linter message.")


class StaticAnalysisReport(BaseModel):
    """Static analysis results generated by Flake8."""

    linter: str = Field(default="flake8", description="Linter engine used.")
    issue_count: int = Field(..., ge=0, description="Total issues detected.")
    issues: List[Flake8Issue] = Field(
        default_factory=list, description="List of detected lint issues."
    )
    clean: bool = Field(..., description="True if no linting violations exist.")


class LLMCodeReview(BaseModel):
    """LLM evaluation covering Big-O algorithmic complexity and edge cases."""

    time_complexity: str = Field(
        ...,
        description="Asymptotic time complexity estimate (e.g., O(N), O(N^2)).",
        examples=["O(N^2)"],
    )
    space_complexity: str = Field(
        ...,
        description="Asymptotic auxiliary space complexity estimate.",
        examples=["O(N)"],
    )
    analysis: str = Field(
        ...,
        description="Detailed review explaining algorithmic behavior and bottlenecks.",
    )
    missing_edge_cases: List[str] = Field(
        default_factory=list,
        description="Potential edge cases unhandled by the implementation.",
    )
    suggested_improvements: List[str] = Field(
        default_factory=list,
        description="Actionable refactoring recommendations.",
    )


class ReviewCodeResponse(BaseModel):
    """Comprehensive code review report combining Flake8 and LLM insights."""

    status: str = Field(default="success", description="Status of the review process.")
    static_analysis: StaticAnalysisReport = Field(..., description="Flake8 linter report.")
    llm_review: LLMCodeReview = Field(..., description="LLM complexity and edge-case review.")


# ==============================================================================
# Health Check Schema
# ==============================================================================

class HealthResponse(BaseModel):
    """Microservice health and telemetry status."""

    status: str = Field(..., examples=["healthy"])
    uptime_seconds: float = Field(..., description="Service uptime in seconds.", examples=[123.45])
    llm_provider: str = Field(
        ..., description="Active LLM provider (bedrock or mock).", examples=["mock"]
    )
    version: str = Field(..., description="Microservice release version.", examples=["1.0.0"])
    environment: str = Field(default="production", description="Environment mode.")
